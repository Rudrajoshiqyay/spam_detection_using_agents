// Generate initial transaction stream
export function generateInitialTransactions(count = 12): LiveTransaction[] {
  return Array.from({ length: count }, (_, i) => {
    const txn = generateMockTransaction()
    txn.timestamp = new Date(Date.now() - (count - i) * 8000).toISOString()
    const decision = generateMockDecision(txn)
    return {
      ...txn,
      decision,
      status: decision.decision === 'block' ? 'blocked' : decision.decision === 'review' ? 'review' : 'approved',
      riskScore: decision.risk_score,
    }
  })
}

