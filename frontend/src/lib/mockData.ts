export function generateChartData(hours = 24): ChartDataPoint[] {
  return Array.from({ length: hours }, (_, i) => {
    const date = new Date(Date.now() - (hours - i) * 3600_000)
    const base = 120 + Math.sin(i * 0.4) * 40 + Math.random() * 20
    const fraud = Math.floor(base * (0.04 + Math.random() * 0.04))
    return {
      time: date.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' }),
      value: Math.floor(base),
      fraud,
      legitimate: Math.floor(base) - fraud,
    }
  })
}

